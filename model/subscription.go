// ==================== 订单锁（防止并发重复处理）====================

var (
	orderLocksMu sync.Mutex
	orderLocks   = make(map[string]*orderLockEntry)
)

type orderLockEntry struct {
	mu  sync.Mutex
	ref int
}

// LockSubscriptionOrder 锁定订阅订单（防止并发回调重复处理）
func LockSubscriptionOrder(tradeNo string) func() {
	orderLocksMu.Lock()
	entry, ok := orderLocks[tradeNo]
	if !ok {
		entry = &orderLockEntry{}
		orderLocks[tradeNo] = entry
	}
	entry.ref++
	orderLocksMu.Unlock()

	entry.mu.Lock()
	return func() {
		entry.mu.Unlock()
		orderLocksMu.Lock()
		entry.ref--
		if entry.ref == 0 {
			delete(orderLocks, tradeNo)
		}
		orderLocksMu.Unlock()
	}
}

